-- Completion: the activity is registered with the advising module; completion follows the grade and the pass grade.
INSERT INTO adv_activity (activity_key, course_id, name)
SELECT CONCAT('assignment:', CAST(a.id AS VARCHAR(20))), a.course_id, a.name FROM asg_assignment a WHERE a.name = 'Assignment 1';

INSERT INTO adv_activity_completion (activity_key, user_id, state, time_modified)
SELECT CONCAT('assignment:', CAST(a.id AS VARCHAR(20))), g.user_id,
       CASE WHEN g.grade >= a.grade_pass THEN 'COMPLETE_PASS' ELSE 'COMPLETE_FAIL' END, g.time_modified
FROM asg_grade g JOIN asg_assignment a ON a.id = g.assignment_id
WHERE a.name = 'Assignment 1';

