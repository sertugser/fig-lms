-- Assignment module (REQ-ASG-01..08). Moodle tables: assign, assign_overrides, assign_user_flags, assign_submission,
-- assign_grades. course_id and user_id are logical references to the course and identity modules.

CREATE TABLE asg_assignment (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id              BIGINT       NOT NULL,
    name                   VARCHAR(255) NOT NULL,
    intro                  TEXT         NOT NULL DEFAULT '',
    -- NULL = boundary disabled (Moodle 0).
    allow_submissions_from TIMESTAMP WITH TIME ZONE,
    due_date               TIMESTAMP WITH TIME ZONE,
    cutoff_date            TIMESTAMP WITH TIME ZONE,
    submission_drafts      BOOLEAN      NOT NULL DEFAULT FALSE,
    require_statement      BOOLEAN      NOT NULL DEFAULT FALSE,
    max_grade              DOUBLE PRECISION NOT NULL DEFAULT 100,
    grade_pass             DOUBLE PRECISION,
    reopen_method          VARCHAR(20)  NOT NULL DEFAULT 'UNTIL_PASS',
    -- -1 = unlimited (Moodle ASSIGN_UNLIMITED_ATTEMPTS).
    max_attempts           INTEGER      NOT NULL DEFAULT 1,
    online_text_enabled    BOOLEAN      NOT NULL DEFAULT FALSE,
    file_enabled           BOOLEAN      NOT NULL DEFAULT TRUE,
    max_files              INTEGER      NOT NULL DEFAULT 20,
    -- 0 = the site or course limit applies.
    max_bytes              BIGINT       NOT NULL DEFAULT 0,
    -- Comma separated extensions, for example ".pdf,.docx"; empty = any type.
    accepted_types         VARCHAR(255) NOT NULL DEFAULT '',
    completion             VARCHAR(10)  NOT NULL DEFAULT 'NONE',
    availability           TEXT,
    grade_item_id          BIGINT REFERENCES grd_item (id),
    time_modified          TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT asg_assignment_reopen CHECK (reopen_method IN ('MANUAL', 'AUTOMATIC', 'UNTIL_PASS')),
    CONSTRAINT asg_assignment_attempts CHECK (max_attempts = -1 OR max_attempts >= 1),
    CONSTRAINT asg_assignment_completion CHECK (completion IN ('NONE', 'SUBMIT', 'GRADE')),
    CONSTRAINT asg_assignment_grade CHECK (max_grade > 0 AND (grade_pass IS NULL OR (grade_pass >= 0 AND grade_pass <= max_grade))),
    CONSTRAINT asg_assignment_files CHECK (max_files >= 0 AND max_bytes >= 0),
    -- REQ-ASG-01 form validation, also enforced by the service with Moodle's messages.
    CONSTRAINT asg_assignment_due CHECK (due_date IS NULL OR allow_submissions_from IS NULL OR due_date > allow_submissions_from),
    CONSTRAINT asg_assignment_cutoff CHECK (cutoff_date IS NULL OR
        ((due_date IS NULL OR cutoff_date >= due_date) AND (allow_submissions_from IS NULL OR cutoff_date >= allow_submissions_from)))
);

-- User overrides of the dates (Moodle assign_overrides with userid). Group overrides are out of scope.
CREATE TABLE asg_override (
    assignment_id          BIGINT NOT NULL REFERENCES asg_assignment (id),
    user_id                BIGINT NOT NULL,
    allow_submissions_from TIMESTAMP WITH TIME ZONE,
    due_date               TIMESTAMP WITH TIME ZONE,
    cutoff_date            TIMESTAMP WITH TIME ZONE,
    PRIMARY KEY (assignment_id, user_id)
);

CREATE TABLE asg_user_flag (
    assignment_id      BIGINT  NOT NULL REFERENCES asg_assignment (id),
    user_id            BIGINT  NOT NULL,
    locked             BOOLEAN NOT NULL DEFAULT FALSE,
    extension_due_date TIMESTAMP WITH TIME ZONE,
    PRIMARY KEY (assignment_id, user_id)
);

CREATE TABLE asg_submission (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id  BIGINT      NOT NULL REFERENCES asg_assignment (id),
    user_id        BIGINT      NOT NULL,
    -- REQ-ASG-06: the first attempt is 0.
    attempt_number INTEGER     NOT NULL,
    status         VARCHAR(10) NOT NULL,
    latest         BOOLEAN     NOT NULL,
    online_text    TEXT,
    time_created   TIMESTAMP WITH TIME ZONE NOT NULL,
    time_modified  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT asg_submission_status CHECK (status IN ('NEW', 'DRAFT', 'SUBMITTED', 'REOPENED')),
    CONSTRAINT asg_submission_attempt UNIQUE (assignment_id, user_id, attempt_number)
);

CREATE TABLE asg_grade (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id  BIGINT  NOT NULL REFERENCES asg_assignment (id),
    user_id        BIGINT  NOT NULL,
    attempt_number INTEGER NOT NULL,
    -- NULL = no grade yet (Moodle -1).
    grade          DOUBLE PRECISION,
    grader_id      BIGINT,
    time_modified  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT asg_grade_attempt UNIQUE (assignment_id, user_id, attempt_number)
);

