-- Grading module: grade categories, grade items, grades (REQ-GRD-01..08).
-- Moodle tables: grade_categories, grade_items, grade_grades. course_id and user_id are logical references.
-- Totals are computed when read (GradeCalculator), so there is no needsupdate flag and no stored total to go stale.

CREATE TABLE grd_category (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id             BIGINT       NOT NULL,
    parent_id             BIGINT REFERENCES grd_category (id),
    fullname              VARCHAR(255) NOT NULL,
    aggregation           VARCHAR(30)  NOT NULL DEFAULT 'MEAN',
    aggregate_only_graded BOOLEAN      NOT NULL DEFAULT TRUE,
    drop_low              INTEGER      NOT NULL DEFAULT 0,
    keep_high             INTEGER      NOT NULL DEFAULT 0,
    CONSTRAINT grd_category_aggregation CHECK (aggregation IN ('MEAN', 'WEIGHTED_MEAN', 'MEDIAN', 'MIN', 'MAX')),
    -- REQ-GRD-04: drop lowest and keep highest exclude each other.
    CONSTRAINT grd_category_limit_rules CHECK (drop_low = 0 OR keep_high = 0),
    CONSTRAINT grd_category_limits_positive CHECK (drop_low >= 0 AND keep_high >= 0)
);

CREATE TABLE grd_item (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id   BIGINT       NOT NULL,
    -- For ACTIVITY and MANUAL items: the category the item is in. For CATEGORY and COURSE items: the category whose
    -- total this item is.
    category_id BIGINT       NOT NULL REFERENCES grd_category (id),
    itemname    VARCHAR(255),
    itemtype    VARCHAR(20)  NOT NULL,
    source      VARCHAR(100),
    grade_min   DOUBLE PRECISION NOT NULL DEFAULT 0,
    grade_max   DOUBLE PRECISION NOT NULL DEFAULT 100,
    grade_pass  DOUBLE PRECISION,
    -- Moodle aggregationcoef: the weight in a weighted mean.
    weight      DOUBLE PRECISION NOT NULL DEFAULT 1,
    hidden      BOOLEAN      NOT NULL DEFAULT FALSE,
    locked      BOOLEAN      NOT NULL DEFAULT FALSE,
    sortorder   INTEGER      NOT NULL DEFAULT 0,
    CONSTRAINT grd_item_type CHECK (itemtype IN ('COURSE', 'CATEGORY', 'ACTIVITY', 'MANUAL')),
    CONSTRAINT grd_item_range CHECK (grade_max > grade_min),
    CONSTRAINT grd_item_source_unique UNIQUE (source)
);

CREATE TABLE grd_grade (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id       BIGINT  NOT NULL REFERENCES grd_item (id),
    user_id       BIGINT  NOT NULL,
    raw_grade     DOUBLE PRECISION,
    final_grade   DOUBLE PRECISION,
    hidden        BOOLEAN NOT NULL DEFAULT FALSE,
    locked        BOOLEAN NOT NULL DEFAULT FALSE,
    grader_id     BIGINT,
    time_modified TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT grd_grade_once UNIQUE (item_id, user_id)
);
