-- Files module (REQ-FIL-01..07): file records. The contents live on disk under fig.files.root, named by their
-- SHA-256 hash, so equal contents are stored once (Moodle mdl_files + filedir).

CREATE TABLE fil_file (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    component    VARCHAR(100) NOT NULL,
    area         VARCHAR(50)  NOT NULL,
    item_id      BIGINT       NOT NULL,
    filename     VARCHAR(255) NOT NULL,
    mimetype     VARCHAR(100) NOT NULL,
    size_bytes   BIGINT       NOT NULL CHECK (size_bytes >= 0),
    content_hash CHAR(64)     NOT NULL,
    user_id      BIGINT       NOT NULL REFERENCES idn_user (id),
    time_created TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fil_file_name_uq UNIQUE (component, area, item_id, filename),
    CONSTRAINT fil_file_name_ck CHECK (filename <> '' AND filename <> '.' AND filename <> '..')
);

CREATE INDEX fil_file_hash_ix ON fil_file (content_hash);
