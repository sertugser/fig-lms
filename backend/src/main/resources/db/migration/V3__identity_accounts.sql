-- Identity module: accounts (REQ-IDN-01, REQ-IDN-06, REQ-IDN-07). Moodle table: user.
-- Course roles are not stored here: a role is always held in a course (course module, crs_role_assignment).

CREATE TABLE idn_user (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username            VARCHAR(100)  NOT NULL,
    -- bcrypt hash with Spring's {id} prefix; NULL = the account cannot log in (sample accounts before startup).
    password_hash       VARCHAR(255),
    firstname           VARCHAR(100)  NOT NULL,
    lastname            VARCHAR(100)  NOT NULL,
    email               VARCHAR(100)  NOT NULL DEFAULT '',
    suspended           BOOLEAN       NOT NULL DEFAULT FALSE,
    deleted             BOOLEAN       NOT NULL DEFAULT FALSE,
    site_admin          BOOLEAN       NOT NULL DEFAULT FALSE,
    sample_account      BOOLEAN       NOT NULL DEFAULT FALSE,
    failed_count        INTEGER       NOT NULL DEFAULT 0,
    last_failed_at      TIMESTAMP WITH TIME ZONE,
    locked_until        TIMESTAMP WITH TIME ZONE,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    password_changed_at TIMESTAMP WITH TIME ZONE,
    -- Moodle checks uniqueness in PHP and with a unique (mnethostid, username) index; here the database enforces it.
    CONSTRAINT idn_user_username_unique UNIQUE (username),
    CONSTRAINT idn_user_username_lowercase CHECK (username = LOWER(username))
);

