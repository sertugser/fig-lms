-- Course module: categories, courses, enrolment methods, user enrolments, course roles (REQ-CRS-01..10).
-- Moodle tables: course_categories, course, enrol, user_enrolments, role_assignments (course context only).
-- user_id columns refer to idn_user.id. They are logical references without a foreign key, because the table belongs
-- to another module; the course module checks the user through identity.api before it writes.

CREATE TABLE crs_category (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL,
    -- NULL instead of Moodle's empty string, so several categories may have none while non-empty ones stay unique.
    idnumber    VARCHAR(100),
    parent_id   BIGINT REFERENCES crs_category (id),
    depth       INTEGER      NOT NULL,
    path        VARCHAR(255) NOT NULL,
    visible     BOOLEAN      NOT NULL DEFAULT TRUE,
    -- Own visibility, kept while a hidden parent hides the category (Moodle visibleold).
    visible_old BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT crs_category_idnumber_unique UNIQUE (idnumber),
    CONSTRAINT crs_category_name_not_blank CHECK (LENGTH(TRIM(name)) > 0)
);

CREATE TABLE crs_course (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT        NOT NULL REFERENCES crs_category (id),
    fullname    VARCHAR(1333) NOT NULL,
    shortname   VARCHAR(255)  NOT NULL,
    idnumber    VARCHAR(100),
    startdate   TIMESTAMP WITH TIME ZONE NOT NULL,
    enddate     TIMESTAMP WITH TIME ZONE,
    visible     BOOLEAN       NOT NULL DEFAULT TRUE,
    show_grades BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    -- REQ-CRS-09 (a): unique in the database, not only in the service (Moodle: PHP check only, index not unique).
    -- Case-sensitive like Moodle on PostgreSQL (REQ-CRS-01 criterion 5); see REQ-CRS-09 (c) for the open decision.
    CONSTRAINT crs_course_shortname_unique UNIQUE (shortname),
    CONSTRAINT crs_course_idnumber_unique UNIQUE (idnumber),
    CONSTRAINT crs_course_dates CHECK (enddate IS NULL OR enddate >= startdate)
);

CREATE TABLE crs_enrol_method (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id            BIGINT      NOT NULL REFERENCES crs_course (id),
    method               VARCHAR(20) NOT NULL,
    enabled              BOOLEAN     NOT NULL,
    default_role         VARCHAR(20) NOT NULL DEFAULT 'STUDENT',
    -- Self enrolment settings (Moodle enrol.enrolperiod, enrolstartdate, enrolenddate, password, customint3, customint6).
    enrol_period_seconds BIGINT,
    enrol_start          TIMESTAMP WITH TIME ZONE,
    enrol_end            TIMESTAMP WITH TIME ZONE,
    enrolment_key        VARCHAR(50),
    max_enrolled         INTEGER     NOT NULL DEFAULT 0,
    allow_new            BOOLEAN     NOT NULL DEFAULT TRUE,
    CONSTRAINT crs_enrol_method_one_per_type UNIQUE (course_id, method),
    CONSTRAINT crs_enrol_method_type CHECK (method IN ('MANUAL', 'SELF', 'GUEST'))
);

CREATE TABLE crs_user_enrolment (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    method_id   BIGINT      NOT NULL REFERENCES crs_enrol_method (id),
    user_id     BIGINT      NOT NULL,
    status      VARCHAR(10) NOT NULL DEFAULT 'ACTIVE',
    -- NULL = no limit (Moodle 0).
    time_start  TIMESTAMP WITH TIME ZONE,
    time_end    TIMESTAMP WITH TIME ZONE,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    modified_by BIGINT,
    CONSTRAINT crs_user_enrolment_once UNIQUE (method_id, user_id),
    CONSTRAINT crs_user_enrolment_status CHECK (status IN ('ACTIVE', 'SUSPENDED')),
    -- REQ-CRS-09 (b): Moodle stores such an enrolment, which can never become active.
    CONSTRAINT crs_user_enrolment_period CHECK (time_end IS NULL OR time_start IS NULL OR time_end > time_start)
);

CREATE TABLE crs_role_assignment (
    course_id BIGINT      NOT NULL REFERENCES crs_course (id),
    user_id   BIGINT      NOT NULL,
    role      VARCHAR(20) NOT NULL,
    PRIMARY KEY (course_id, user_id, role),
    CONSTRAINT crs_role_assignment_role CHECK (role IN ('STUDENT', 'TEACHER', 'EDITING_TEACHER', 'MANAGER'))
);

