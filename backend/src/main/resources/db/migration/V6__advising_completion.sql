-- Advising module, step 2: the prerequisite tables refer to course and user ids of the course and identity modules,
-- and activity and course completion are added (REQ-ADV-01..09).
-- Moodle tables: course_completion_criteria, course_completion_aggr_methd, course_completion_crit_compl,
-- course_completions, course_modules_completion.

-- 1. Prerequisites: from short names to course ids. The old tables of V1 are copied, then dropped.
CREATE TABLE adv_course_prerequisite (
    course_id       BIGINT NOT NULL,
    prerequisite_id BIGINT NOT NULL,
    PRIMARY KEY (course_id, prerequisite_id),
    CONSTRAINT adv_course_prerequisite_not_self CHECK (course_id <> prerequisite_id)
);
INSERT INTO adv_course_prerequisite (course_id, prerequisite_id)
SELECT c.id, p.id FROM adv_prerequisite old
JOIN crs_course c ON c.shortname = old.course
JOIN crs_course p ON p.shortname = old.prerequisite;

-- 2. Course completion: same meaning as Moodle course_completions (complete when time_completed is set).
CREATE TABLE adv_course_completion_new (
    course_id      BIGINT NOT NULL,
    user_id        BIGINT NOT NULL,
    time_completed TIMESTAMP WITH TIME ZONE,
    PRIMARY KEY (course_id, user_id)
);
INSERT INTO adv_course_completion_new (course_id, user_id, time_completed)
SELECT c.id, u.id, old.time_completed FROM adv_course_completion old
JOIN crs_course c ON c.shortname = old.course
JOIN idn_user u ON u.username = old.username;

DROP TABLE adv_prerequisite;
DROP TABLE adv_course_completion;
DROP TABLE adv_student;
DROP TABLE adv_course;
ALTER TABLE adv_course_completion_new RENAME TO adv_course_completion;

-- 3. Activities that restrictions and completion criteria can refer to, and each user's state.
CREATE TABLE adv_activity (
    activity_key VARCHAR(100) PRIMARY KEY,
    course_id    BIGINT       NOT NULL,
    name         VARCHAR(255) NOT NULL,
    deleted      BOOLEAN      NOT NULL DEFAULT FALSE
);

CREATE TABLE adv_activity_completion (
    activity_key  VARCHAR(100) NOT NULL REFERENCES adv_activity (activity_key),
    user_id       BIGINT       NOT NULL,
    state         VARCHAR(20)  NOT NULL,
    time_modified TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (activity_key, user_id),
    CONSTRAINT adv_activity_completion_state CHECK (state IN ('INCOMPLETE', 'COMPLETE', 'COMPLETE_PASS', 'COMPLETE_FAIL'))
);

-- 4. Course completion criteria (REQ-ADV-05). One row per criterion; the columns used depend on the type.
CREATE TABLE adv_completion_criterion (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id       BIGINT      NOT NULL,
    criterion_type  VARCHAR(20) NOT NULL,
    activity_key    VARCHAR(100),
    other_course_id BIGINT,
    role            VARCHAR(20),
    grade_pass      DOUBLE PRECISION,
    time_end        TIMESTAMP WITH TIME ZONE,
    CONSTRAINT adv_completion_criterion_type CHECK (criterion_type IN ('SELF', 'DATE', 'ACTIVITY', 'GRADE', 'ROLE', 'COURSE'))
);

-- Aggregation per course and criterion type; criterion_type 'OVERALL' is the overall method. No row = ALL.
CREATE TABLE adv_completion_aggregation (
    course_id      BIGINT      NOT NULL,
    criterion_type VARCHAR(20) NOT NULL,
    method         VARCHAR(3)  NOT NULL,
    PRIMARY KEY (course_id, criterion_type),
    CONSTRAINT adv_completion_aggregation_method CHECK (method IN ('ALL', 'ANY'))
);

-- Criteria a person marks: ROLE (a teacher marks the student complete) and SELF (the student marks themself).
CREATE TABLE adv_criterion_mark (
    criterion_id   BIGINT NOT NULL REFERENCES adv_completion_criterion (id),
    user_id        BIGINT NOT NULL,
    marked_by      BIGINT NOT NULL,
    time_completed TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (criterion_id, user_id)
);
